import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const DIST = resolve(ROOT, "dist");

const gcData = JSON.parse(readFileSync(resolve(ROOT, "src/data/gamechangers.json"), "utf-8"));

const matches = [];
for (const [sKey, season] of Object.entries(gcData.seasons)) {
  for (const m of season.matches) {
    if (m.homeScore === 0 && m.awayScore === 0 && m.gamechanger1?.type === "unknown") continue;
    matches.push({ season: sKey, match: m });
  }
}

const lines = [
  "# Auto-generated by generate-redirects.mjs — do not edit manually",
  "",
];

for (const [idx, { season, match }] of matches.entries()) {
  const slug = `s${season}-${match.homeSlug}-vs-${match.awaySlug}-gw${match.gameweek}`;
  lines.push(`/match/${idx + 1}/  /match/${slug}/  301`);
}

lines.push("");
lines.push("# Redirect old /match/s3-* format to /news/ (previous routing scheme)");
lines.push("/match/s3-*  /news/:splat  301");
lines.push("");

writeFileSync(resolve(DIST, "_redirects"), lines.join("\n"), "utf-8");

console.log(`✓ Generated ${matches.length} match ID redirects → dist/_redirects`);
